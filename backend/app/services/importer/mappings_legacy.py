# -*- coding: utf-8 -*-
"""招商证券**旧版导出格式**（2020 年及以前）的声明式别名表。

## 为什么单独一个文件

`mappings.py` 已贴着 services 体量闸门（`scripts/guard_service_size.py`）的基线，而旧版
兼容用的三张表（列名 / 业务名 / 金额符号）与新版映射表**没有任何交叉**——它们描述的是
「另一套导出格式」，不是新增业务。放在一起只会让两个格式的口径互相污染。

## 旧版与新版的差异（2020 年真实交割单 175 行逐行实证）

旧版是 11 列纯 TSV：`证券代码 / 证券名称 / 买卖标志 / 成交日期 / 成交时间 / 成交价格 /
成交数量 / 成交金额 / 成交编号 / 委托编号 / 股东代码`，没有「业务名称」「发生金额」
「费用明细」「币种」「剩余数量」。有三处会改变**数值口径**：

1. 方向列叫「买卖标志」，取值只有「买入 / 卖出」→ :data:`CMS_LEGACY_OP_ALIASES`；
2. 「成交金额」**恒为正数**：同一笔打新里「中签扣款」与「扣款回冲」都是 +1000，方向只
   靠业务名与「成交数量」的正负体现。打新折叠器按组内现金流**净额**算本金
   （`ipo_events.py` 口径 ①），吃正数会把 1000 元算成 3000 元 → :data:`CMS_LEGACY_AMOUNT_SIGNS`；
3. 旧版把**报价回购也记成「买入 / 卖出」**（2020 样本 36 行，价格 1.38 是年化收益率、
   金额 1000 是本金，`金额 / (价格×数量) ≈ 72.5`）。新版靠业务名「报价回购拆出 /
   报价购回卖」就能排除，旧版只能靠**等比判据**（见 `parsers/cms_stock.py` 的
   `_is_market_trade`）：真实证券成交恒有 `|金额| ≈ 价格 × 数量`。
"""

CMS_LEGACY_COLUMN_ALIASES = {
    '买卖标志': '业务名称',
    '成交金额': '发生金额',
    '成交编号': '流水号',
    '委托编号': '合同编号',
}

# 旧版只有「买入 / 卖出」，没有「证券买入 / 证券卖出」。
CMS_LEGACY_OP_ALIASES = {
    '买入': '证券买入',
    '卖出': '证券卖出',
}

# 旧版「成交金额」恒为正，方向要按业务名补回符号（负=资金流出）。
CMS_LEGACY_AMOUNT_SIGNS = {
    '证券买入': -1,
    '证券卖出': 1,
    '市值申购中签扣款': -1,
    '新股申购确认缴款': -1,
    '市值申购中签扣款回冲': 1,
    # 以下两项无 2020 样本，按语义兜底：旧版若出现银证转账，符号同样会丢
    '银行转取': -1,
    '银行转存': 1,
}

# 旧版独有的非交易行：交易单元「指定 / 撤指定」，无资金、无持仓变动。
CMS_LEGACY_IGNORED_OPS = frozenset({'指定或撤指定'})
