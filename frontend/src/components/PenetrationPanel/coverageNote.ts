/**
 * 穿透覆盖率的「作用域口径」提示（#2595 验收第 3 条）。
 *
 * ## 为什么必须单独说一句
 *
 * 穿透覆盖率有硬上限：直持股票缺「个股→行业」映射、场内 ETF 缺底层持仓、货基债基
 * 本身没有股票敞口。家庭级本机实测约 53%——这已经是「一半的钱看不透」。
 *
 * 拆到账户 / 组合后，分母骤减：同样一只科创 ETF 在一个小账户里可能占 40%，在家庭级
 * 只占 3%。于是**覆盖率在小作用域里波动更大**，而面板上的「已穿透 40%」看起来与
 * 家庭级的「40%」一样权威——这正是 #2595 要求「按账户拆分时覆盖率波动有提示文案」
 * 的原因：不给这句话，用户会把两个不可比的数当成同一条基准线上的读数。
 *
 * ## 措辞上的两条约束
 *
 * 1. **不写具体百分比**（如「上限 53%」）：那是本机某次实测值，会随持仓结构漂移；
 *    写死在文案里，一年后就成了错误断言。这里只说「有硬上限 + 为什么」。
 * 2. **明确「不可比」而不仅是「波动」**：只说「会波动」，用户仍可能拿两个账户的
 *    覆盖率去比大小；只有说「不可直接比大小」，才堵住这个误读。
 *
 * 家庭级返回空串（调用方据此不渲染）——家庭级是这套指标的基准线本身，不需要再解释
 * 「它相对谁波动」。
 */

/** 穿透口径（与后端出参 `scope` 同源） */
export type PenetrationScope = "family" | "ledger" | "portfolio";

/** 三个「穿透看不透」的成因，账户档与组合档共用一份措辞（避免两处各写一版） */
const CAP_REASON =
  "直持股票缺行业映射、场内 ETF 缺底层持仓、货基债基本身无股票敞口";

const LEDGER_NOTE =
  `按账户拆开后，每个账户的持仓基数都变小，覆盖率会比家庭级波动更大（${CAP_REASON}，` +
  "覆盖率本就有硬上限）——不同账户之间的覆盖率不可直接比大小，只适合同向参考。";

const PORTFOLIO_NOTE =
  "组合级只统计该组合归属的持仓，覆盖率与家庭级不可直接比大小——" +
  `组合越小、分母越小，波动越明显（${CAP_REASON}）。`;

/**
 * 覆盖率作用域提示。
 *
 * @param scope 后端出参的 `scope`；`undefined`（旧响应 / 未加载）按家庭级处理，
 *   不猜作用域——猜错会把「账户级覆盖率高」说成「需要提醒」，比不说更糟。
 * @returns 家庭级返回 `""`（不渲染）；账户 / 组合级各返回一句。
 */
export function coverageScopeNote(scope: PenetrationScope | undefined): string {
  if (scope === "ledger") return LEDGER_NOTE;
  if (scope === "portfolio") return PORTFOLIO_NOTE;
  return "";
}
